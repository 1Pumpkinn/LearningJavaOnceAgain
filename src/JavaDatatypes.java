public class JavaDatatypes {

    public JavaDatatypes() {

        // Integers (Store whole numbers including negative numbers)
        // Ints go from -2147483648 to 2147483647

        /* Variables */

        // datatype name_of_variable; //Declaration
        // OR
        // Datatype name_of_variables = value_of_variable; // Initialization (Declaration + Assignment of Value)

        // Every instruction/line ends with a semicolon ;
        // int y = 42 <-- will error.

        int points;
        points = 100;
        int x = -100;

        // Floating Points Numbers (float & double)
        float pi = 3.14159265f;
        double e = 2.718281828;

        float accountValue = 20.20f; // DO NOT DO THIS!

        // For real numbers, however! Precision can be an issue!
        // Scientific notation 314159265 * 10^-8

        // Booleans (True or False)
        boolean youAreCute = true;
        boolean youAreAmazing = false;
        boolean isPlayerAlive = true;
        boolean isPlayerInArea;

        // Chars & Strings
        char grade = 'B'; // One Character
        char number = '0';
        String name = "Rose";
        String ID = "3499435KKAW349394LEDSDQ94Q";
    }
}
